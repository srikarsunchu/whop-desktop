import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const js=ts.transpileModule(fs.readFileSync('src/lib/campaign-editor.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ES2022}}).outputText;
const {campaignCommand}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
assert.throws(()=>campaignCommand('ad-campaigns',undefined,{title:'Test',objective:'traffic'}),/budget/);
assert.throws(()=>campaignCommand('ad-campaigns','id',{title:'Test',budget_amount:'-5'}),/greater than zero/);
const create=campaignCommand('ad-campaigns',undefined,{title:'Test',objective:'traffic',budget_amount:'25',budget_type:'daily'},undefined,'stable-key');
assert.ok(!create.includes('--status'),'Creating campaign must not launch it');
assert.equal(create[create.indexOf('--idempotency-key')+1],'stable-key');
const group=campaignCommand('ad-groups',undefined,{title:'Audience',regions:'{"include":{"countries":["US"]}}',placements:'automatic'},'campaign');
assert.equal(group[group.indexOf('--status')+1],'paused');
assert.throws(()=>campaignCommand('ad-groups',undefined,{title:'Group'}),/parent/);
assert.throws(()=>campaignCommand('ad-groups','id',{title:'Group',regions:'{"include":{"countries":["USA"]}}'}),/two-letter/);
assert.throws(()=>campaignCommand('ads','id',{title:'Ad',url:'javascript:alert(1)'}),/HTTPS/);
const ad=campaignCommand('ads','id',{title:'Ad',headlines:'A "quote"',primary_texts:'First\nSecond',url:'https://example.com'});
assert.deepEqual(JSON.parse(ad[ad.indexOf('--headlines')+1]),['A "quote"']);
assert.throws(()=>campaignCommand('ad-campaigns','id',{title:'A',starts_at:'2026-10-10',ends_at:'2026-10-09'}),/after/);
console.log('Campaign validation passed: draft creation, paused groups, budget, targeting, HTTPS, dates, idempotency and copy encoding.');
